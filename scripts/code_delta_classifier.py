# Outcome contract (scripts/OUTCOME_CONTRACT.md): the four outcomes and the
# argparse override. A usage violation exits 3 with a final `OUTCOME:
# tool_error` line on stderr before exit; `--help` stays a metadata exit
# without an `OUTCOME:` line; every classified run's final line is on stdout.
OUTCOME_LABELS = {0: "pass", 1: "fail", 2: "indeterminate", 3: "tool_error"}


class OutcomeArgumentParser(argparse.ArgumentParser):
    """Argument parser whose usage errors exit 3 (tool error) with a final
    `OUTCOME: tool_error` line on stderr before exit, overriding argparse's
    default exit 2; `--help` stays a metadata exit without an `OUTCOME:`
    line."""

    def error(self, message):
        self.print_usage(sys.stderr)
        sys.stderr.write("%s: error: %s\n" % (self.prog, message))
        sys.stderr.write("OUTCOME: %s\n" % OUTCOME_LABELS[3])
        raise SystemExit(3)


def emit_outcome(code):
    print("OUTCOME: %s" % OUTCOME_LABELS[code])


def indeterminate(message):
    """A git plumbing failure over already-resolved inputs (exit 2, never
    a domain finding)."""
    sys.stderr.write("code-delta-classifier: %s\n" % message)
    emit_outcome(2)
    return 2


def tool_error(message):
    """An input that never resolved (operand, ref) (exit 3)."""
    sys.stderr.write("code-delta-classifier: %s\n" % message)
    emit_outcome(3)
    return 3


def load_receipt(path):
    """The receipt operand as a JSON object; schema errors surface through
    corrections_record's row validation at build time."""
    raw = Path(path).read_bytes()
    doc = json.loads(raw.decode("utf-8"))
    if not isinstance(doc, dict):
        raise cr.CorrectionsSchemaError(
            cr.leg_reason("schema", "receipt operand is not a JSON object"))
    return doc


def _utc_now():
    from datetime import datetime, timezone
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def main(argv=None):
    parser = OutcomeArgumentParser(
        prog="code_delta_classifier.py",
        description="Classify a committed code fix between two heads over "
                    "a merge base and emit corrections rows.")
    parser.add_argument("--fix-commits", nargs=2, required=True,
                        metavar=("before-head", "after-head"),
                        help="the certified before head and the fix's "
                             "after head")
    parser.add_argument("--base", required=True,
                        help="the merge base ref of the certified range")
    parser.add_argument("--repo", required=True,
                        help="the repository root")
    parser.add_argument("--emit-row", action="store_true",
                        help="print the corrections row as one JSON line")
    parser.add_argument("--kind",
                        choices=(cr.KIND_SCRIPT_VERIFIED,
                                 cr.KIND_OPERATOR_ACKED),
                        default=cr.KIND_SCRIPT_VERIFIED)
    parser.add_argument("--receipt",
                        help="receipt JSON operand for the operator-acked "
                             "kind")
    parser.add_argument("--ack-witness",
                        help="witness record path the operator-acked "
                             "receipt resolves against; echoed beside the "
                             "row (the validator grades the receipt "
                             "against its own context witness)")
    args = parser.parse_args(argv)
    if args.kind == cr.KIND_OPERATOR_ACKED and not args.receipt:
        return tool_error("--kind operator-acked requires --receipt "
                          "<receipt-json>")
    if args.receipt and args.kind != cr.KIND_OPERATOR_ACKED:
        return tool_error("--receipt requires --kind operator-acked")
    if args.ack_witness and args.kind != cr.KIND_OPERATOR_ACKED:
        return tool_error("--ack-witness requires --kind operator-acked")
    toplevel = cr.git_text(args.repo, "rev-parse", "--show-toplevel")
    if toplevel is None:
        return tool_error("the --repo operand %s is not inside a git "
                          "repository" % args.repo)
    root = toplevel.strip()
    base = cr.resolve_commit(root, args.base)
    if base is None:
        return tool_error("the --base ref %r does not resolve to a commit"
                          % args.base)
    before = cr.resolve_commit(root, args.fix_commits[0])
    if before is None:
        return tool_error("the before head %r does not resolve to a "
                          "commit" % args.fix_commits[0])
    after = cr.resolve_commit(root, args.fix_commits[1])
    if after is None:
        return tool_error("the after head %r does not resolve to a "
                          "commit" % args.fix_commits[1])
    before_diff = cr.diff_bytes(root, base, before)
    if before_diff is None:
        return indeterminate("git diff %s...%s failed over resolved refs"
                             % (base, before))
    after_diff = cr.diff_bytes(root, before, after)
    if after_diff is None:
        return indeterminate("git diff %s...%s failed over resolved refs"
                             % (before, after))
    print("repo: %s" % root)
    print("base: %s" % base)
    print("before head: %s" % before)
    print("after head: %s" % after)
    print("before diff digest: %s" % cr.sha256_hex(before_diff))
    print("after diff digest: %s" % cr.sha256_hex(after_diff))
    if before == after:
        print("refusal: %sno fix to classify: the before and after heads "
              "resolve the identical commit; with the fix left "
              "uncommitted the correction is unclassifiable and the "
              "default re-review applies" % cr.MARKER_PREFIX)
        emit_outcome(1)
        return 1
    if not after_diff.strip():
        print("refusal: %sno fix to classify: the fix diff is empty; the "
              "correction hop is unclassifiable and the default re-review "
              "applies" % cr.MARKER_PREFIX)
        emit_outcome(1)
        return 1
    total_hunks = []
    all_ok = True
    first_failure = None
    classified_any = False
    excluded = []
    for section in diff_sections(after_diff):
        refusal = section_refusal(section)
        if refusal is not None:
            all_ok = False
            if first_failure is None:
                first_failure = cr.leg_reason("classify", refusal)
            continue
        old, new = section["old"], section["new"]
        path = new if new is not None else old
        if path is None:
            continue
        if seal_excluded(path):
            excluded.append(path)
            continue
        before_path = old if old is not None else path
        after_path = new if new is not None else path
        old_bytes, old_absent, err = _read_side(root, before, before_path)
        refusal = None
        if err is None:
            new_bytes, new_absent, err = _read_side(root, after, after_path)
        if err is None and old_absent and old is not None:
            refusal = _side_absent_refusal(old, "before", before)
        if err is None and refusal is None and new_absent \
                and new is not None:
            refusal = _side_absent_refusal(new, "after", after)
        if refusal is not None:
            all_ok = False
            if first_failure is None:
                first_failure = cr.leg_reason(
                    "classify", "%s: %s" % (path, refusal))
            continue
        if err is not None:
            return indeterminate("%s: %s" % (path, err))
        for side, blob in (("before", old_bytes), ("after", new_bytes)):
            try:
                blob.decode("utf-8")
            except UnicodeDecodeError as exc:
                return tool_error("the %s blob of %s is not decodable "
                                  "UTF-8 text: %s" % (side, path, exc))
        classified_any = True
        print("path: %s language: %s" % (path, language_of(path)))
        hunks, ok, message = classify_delta(old_bytes, new_bytes, path)
        for offset, hunk in enumerate(hunks, 1):
            print("hunk %d: %s %s (%s)"
                  % (len(total_hunks) + offset, hunk["header"],
                     hunk["class"], hunk["reason"]))
        total_hunks.extend(hunks)
        if not ok:
            all_ok = False
            if first_failure is None:
                first_failure = message
    for path in excluded:
        print("excluded (seal path): %s" % path)
    if not classified_any:
        ok = False
        message = cr.leg_reason("classify", NO_CLASSIFIABLE_REASON)
    elif all_ok:
        ok, message = exempt_verdict(total_hunks)
    else:
        ok, message = False, first_failure
    if ok:
        print("verdict: %s" % message)
    else:
        print("refusal: %s" % message)
    if args.emit_row:
        if not total_hunks:
            print("no row: a corrections row is never vacuous")
        elif not ok and args.kind != cr.KIND_OPERATOR_ACKED:
            print("no row: a script-verified row requires every hunk "
                  "exempt; the ack path is --kind operator-acked "
                  "--receipt")
        else:
            row = {
                "kind": args.kind,
                "before_digest": cr.sha256_hex(before_diff),
                "after_digest": cr.sha256_hex(after_diff),
                "before_base": base,
                "before_head": before,
                "after_base": before,
                "after_head": after,
                "hunks": [{"header": hunk["header"],
                           "digest": hunk["digest"]}
                          for hunk in total_hunks],
                "recorded_at": _utc_now(),
                "recorded_by": "code_delta_classifier",
            }
            try:
                receipt = load_receipt(args.receipt) \
                    if args.kind == cr.KIND_OPERATOR_ACKED else None
                if receipt is not None:
                    row["receipt"] = receipt
                cr.validate_row(row, cr.FAMILY_CODE)
            except (OSError, ValueError, UnicodeDecodeError) as exc:
                return tool_error("the receipt operand %s is unreadable "
                                  "or not decodable JSON: %s"
                                  % (args.receipt, exc))
            except cr.CorrectionsSchemaError as exc:
                return tool_error(str(exc))
            if args.ack_witness:
                print("ack-witness: %s" % args.ack_witness)
            print("corrections-row-json: %s" % json.dumps(row,
                                                          sort_keys=True))
    emit_outcome(0 if ok else 1)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
