# Per-language line models
# ---------------------------------------------------------------------------


def _string_token_types():
    types = [tokenize.STRING]
    for name in ("FSTRING_START", "FSTRING_MIDDLE", "FSTRING_END"):
        if hasattr(tokenize, name):
            types.append(getattr(tokenize, name))
    return tuple(types)


_STRING_TOKENS = _string_token_types()


def _docstring_spans(tree):
    """(first_line, last_line) spans of module, class, and function
    docstrings: the first statement being a bare string literal."""
    spans = []

    def first_statement(body):
        if not body:
            return
        first = body[0]
        if not isinstance(first, ast.Expr):
            return
        value = first.value
        if isinstance(value, ast.Constant) and isinstance(value.value, str):
            spans.append((first.lineno, first.end_lineno))
        elif isinstance(value, ast.JoinedStr):
            spans.append((first.lineno, first.end_lineno))

    first_statement(tree.body)
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef,
                             ast.ClassDef)):
            first_statement(node.body)
    return spans


def _python_model(text):
    """Per-line records for the Python proof, or None when the file does
    not tokenize or parse (fail-closed). ``code`` is the line with the
    comment token span removed; ``docstring`` marks lines inside a
    docstring span or a multi-line string literal; the line-1 shebang is
    code, never a comment."""
    lines = _split_lines(text)
    try:
        tokens = list(tokenize.generate_tokens(io.StringIO(text).readline))
        tree = ast.parse(text)
    except (tokenize.TokenError, SyntaxError, ValueError):
        return None
    comments = {}
    in_string = set()
    for tok in tokens:
        if tok.type == tokenize.COMMENT:
            comments.setdefault(tok.start[0], []).append(
                (tok.start[1], tok.end[1]))
        elif tok.type in _STRING_TOKENS and tok.end[0] > tok.start[0]:
            in_string.update(range(tok.start[0] + 1, tok.end[0]))
    docstrings = _docstring_spans(tree)
    records = []
    for index, line in enumerate(lines):
        lineno = index + 1
        code = line
        comment = None
        shebang = lineno == 1 and line.startswith("#!")
        if not shebang:
            spans = sorted(comments.get(lineno, []))
            if spans:
                start, end = spans[0]
                comment = line[start:end]
                code = line[:start]
        records.append({
            "line": line,
            "code": code,
            "comment": comment,
            "shebang": shebang,
            "docstring": (any(s <= lineno <= e for s, e in docstrings)
                          or lineno in in_string),
        })
    return records


def _bash_model(text):
    """Per-line records for the Bash proof: quote state (single, double,
    and backslash escapes) and heredoc state carry across lines; a hash
    starts a comment only at a word boundary outside quotes; heredoc body
    lines are data; the line-1 shebang is code, never a comment."""
    lines = _split_lines(text)
    records = []
    in_single = False
    in_double = False
    heredoc = None
    for line in lines:
        if heredoc is not None:
            delim, strip_tabs = heredoc
            candidate = line.lstrip("\t") if strip_tabs else line
            body = candidate != delim
            if not body:
                heredoc = None
            records.append({"line": line, "code": line, "comment": None,
                            "shebang": False, "heredoc": body,
                            "quote_cont": False})
            continue
        if not records and line.startswith("#!"):
            records.append({"line": line, "code": line, "comment": None,
                            "shebang": True, "heredoc": False,
                            "quote_cont": False})
            continue
        quote_cont = in_single or in_double
        code = line
        comment = None
        pending = None
        i = 0
        n = len(line)
        while i < n:
            ch = line[i]
            if in_single:
                if ch == "'":
                    in_single = False
                i += 1
                continue
            if in_double:
                if ch == "\\":
                    i += 2
                    continue
                if ch == '"':
                    in_double = False
                i += 1
                continue
            if ch == "\\":
                i += 2
                continue
            if ch == "'":
                in_single = True
                i += 1
                continue
            if ch == '"':
                in_double = True
                i += 1
                continue
            if ch == "<":
                if i == 0 or line[i - 1] != "<":
                    match = _HEREDOC_RE.match(line, i)
                    if match:
                        pending = (match.group(3), match.group(1) == "-")
                        i = match.end()
                        continue
                i += 1
                continue
            if ch == "#" and (i == 0 or line[i - 1] in " \t"):
                comment = line[i:]
                code = line[:i]
                break
            i += 1
        if pending is not None:
            heredoc = pending
        records.append({"line": line, "code": code, "comment": comment,
                        "shebang": False, "heredoc": False,
                        "quote_cont": quote_cont})
    return records


# ---------------------------------------------------------------------------
# Verdicts
# ---------------------------------------------------------------------------


def _pair_verdict(old_records, new_records, old_index, new_index, language):
    old = old_records[old_index]
    new = new_records[new_index]
    if language == "python":
        for rec in (old, new):
            if rec["docstring"]:
                return CLASS_UNCLASSIFIED, REASON_DOCSTRING
    else:
        for rec in (old, new):
            if rec["heredoc"]:
                return CLASS_UNCLASSIFIED, REASON_HEREDOC
            if rec["quote_cont"]:
                return CLASS_UNCLASSIFIED, REASON_QUOTE
    if old["shebang"] or new["shebang"]:
        return CLASS_UNCLASSIFIED, REASON_SHEBANG
    member = _directive_member(old["comment"]) or \
        _directive_member(new["comment"])
    if member is not None:
        return CLASS_UNCLASSIFIED, _directive_reason(member)
    if not old["line"].strip() and not new["line"].strip():
        return CLASS_UNCLASSIFIED, REASON_BLANK
    if old["code"] != new["code"]:
        return CLASS_UNCLASSIFIED, REASON_CODE_CHANGED
    return CLASS_COMMENT_ONLY, ("comment content changed with the code "
                                "portion byte-identical")


def _side_verdict(record, direction, language):
    if language == "python" and record["docstring"]:
        return CLASS_UNCLASSIFIED, REASON_DOCSTRING
    if language == "bash":
        if record["heredoc"]:
            return CLASS_UNCLASSIFIED, REASON_HEREDOC
        if record["quote_cont"]:
            return CLASS_UNCLASSIFIED, REASON_QUOTE
    if record["shebang"]:
        return CLASS_UNCLASSIFIED, REASON_SHEBANG
    member = _directive_member(record["comment"])
    if member is not None:
        return CLASS_UNCLASSIFIED, _directive_reason(member)
    if not record["line"].strip():
        return CLASS_UNCLASSIFIED, REASON_BLANK
    if record["code"].strip() == "":
        if direction == "removed":
            return CLASS_COMMENT_ONLY, "a full-line comment was removed"
        return CLASS_COMMENT_ONLY, "a full-line comment was added"
    if direction == "removed":
        return CLASS_UNCLASSIFIED, REASON_CODE_REMOVED
    return CLASS_UNCLASSIFIED, REASON_CODE_ADDED


# ---------------------------------------------------------------------------
# Hunk scaffolding (mirrors plan_delta_classifier's contract)
# ---------------------------------------------------------------------------


def _change_groups(opcodes):
    groups = []
    current = None
    for tag, i1, i2, j1, j2 in opcodes:
        if tag == "equal":
            if current is not None:
                groups.append(tuple(current))
                current = None
            continue
        if current is None:
            current = [i1, i2, j1, j2]
        else:
            current[1] = i2
            current[3] = j2
    if current is not None:
        groups.append(tuple(current))
    return groups


def _hunk_header(old_lines, new_lines, i1, i2, j1, j2):
    old_count = i2 - i1
    new_count = j2 - j1
    old_start = i1 + 1 if old_count else i1
    new_start = j1 + 1 if new_count else j1
    return "@@ -%d,%d +%d,%d @@" % (old_start, old_count, new_start,
                                    new_count)


def _hunk_digest(old_lines, new_lines, i1, i2, j1, j2):
    payload = b"\n".join(
        [("-" + line).encode("utf-8") for line in old_lines[i1:i2]]
        + [("+" + line).encode("utf-8") for line in new_lines[j1:j2]])
    return cr.sha256_hex(payload)


def _classify_hunk(context, i1, i2, j1, j2):
    members = []
    shared = min(i2 - i1, j2 - j1)
    for offset in range(shared):
        members.append(_pair_verdict(context["old_records"],
                                     context["new_records"],
                                     i1 + offset, j1 + offset,
                                     context["language"]))
    for old_index in range(i1 + shared, i2):
        members.append(_side_verdict(context["old_records"][old_index],
                                     "removed", context["language"]))
    for new_index in range(j1 + shared, j2):
        members.append(_side_verdict(context["new_records"][new_index],
                                     "added", context["language"]))
    if not members:
        return None
    classes = {klass for klass, _ in members}
    if classes == {CLASS_UNCLASSIFIED} or len(classes) > 1:
        refusal = next((reason for klass, reason in members
                        if klass == CLASS_UNCLASSIFIED), None)
        if refusal is None:
            refusal = ("a hunk mixing verdicts carries no single exempt "
                       "class")
        return CLASS_UNCLASSIFIED, refusal
    return members[0]


# ---------------------------------------------------------------------------
# Classification entry points
# ---------------------------------------------------------------------------


def _split_lines(text):
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return lines


def language_of(path):
    return LANGUAGE_BY_SUFFIX.get(os.path.splitext(str(path))[1].lower())


def unsupported_reason(path):
    suffix = os.path.splitext(str(path))[1] or "(no extension)"
    return ("no classifier support for %s files at birth (supported "
            "languages: Python and Bash); the language fails closed"
            % suffix)


def generated_marker_reason(old_text, new_text):
    for text in (old_text, new_text):
        for line in text.split("\n")[:_GENERATED_HEADER_LINES]:
            lowered = line.lower()
            if any(marker in lowered for marker in GENERATED_MARKERS):
                return ("generated files are excluded: the content carries "
                        "a generated-file marker header (%r)" % line)
    return None


def _whole_file_hunk(old_bytes, new_bytes, reason):
    return {"header": "@@ whole file @@",
            "digest": cr.sha256_hex(old_bytes + b"\x00" + new_bytes),
            "class": CLASS_UNCLASSIFIED,
            "reason": reason}


def _cookie_refusal(old_lines, new_lines, old_bytes, new_bytes):
    """The lines-1-2 encoding-declaration refusal: a line 1 or 2 change
    where either side carries a PEP 263 coding spelling."""
    for index in (0, 1):
        old_line = old_lines[index] if index < len(old_lines) else None
        new_line = new_lines[index] if index < len(new_lines) else None
        if old_line == new_line:
            continue
        for line in (old_line, new_line):
            if line is not None and _PEP263_RE.match(line):
                return {"header": "@@ lines 1-2 @@",
                        "digest": cr.sha256_hex(old_bytes + b"\x00"
                                                + new_bytes),
                        "class": CLASS_UNCLASSIFIED,
                        "reason": REASON_COOKIE}
    return None


def classify_lines(old_bytes, new_bytes, path):
    """The hunk list for one file's byte delta; each hunk carries
    ``header``, ``digest``, ``class`` and the ``reason`` naming the rule
    applied or violated. Identical bytes give no hunks."""
    if old_bytes == new_bytes:
        return []
    lang = language_of(path)
    if lang is None:
        return [_whole_file_hunk(old_bytes, new_bytes,
                                 unsupported_reason(path))]
    try:
        old_text = old_bytes.decode("utf-8")
        new_text = new_bytes.decode("utf-8")
    except UnicodeDecodeError as exc:
        return [_whole_file_hunk(
            old_bytes, new_bytes,
            "the file content is not decodable as UTF-8 text (%s); the "
            "delta fails closed" % exc)]
    generated = generated_marker_reason(old_text, new_text)
    if generated is not None:
        return [_whole_file_hunk(old_bytes, new_bytes, generated)]
    builder = _python_model if lang == "python" else _bash_model
    old_records = builder(old_text)
    new_records = builder(new_text)
    if old_records is None or new_records is None:
        return [_whole_file_hunk(
            old_bytes, new_bytes,
            "the file does not tokenize or parse under the %s proof; the "
            "delta fails closed" % lang)]
    old_lines = [record["line"] for record in old_records]
    new_lines = [record["line"] for record in new_records]
    if lang == "python":
        cookie = _cookie_refusal(old_lines, new_lines, old_bytes, new_bytes)
        if cookie is not None:
            return [cookie]
    context = {"old_records": old_records, "new_records": new_records,
               "language": lang}
    matcher = difflib.SequenceMatcher(a=old_lines, b=new_lines,
                                      autojunk=False)
    hunks = []
    for i1, i2, j1, j2 in _change_groups(matcher.get_opcodes()):
        verdict = _classify_hunk(context, i1, i2, j1, j2)
        if verdict is None:
            continue
        klass, reason = verdict
        hunks.append({
            "header": _hunk_header(old_lines, new_lines, i1, i2, j1, j2),
            "digest": _hunk_digest(old_lines, new_lines, i1, i2, j1, j2),
            "class": klass,
            "reason": reason,
        })
    return hunks


def bytes_changed_no_hunks_reason(old_bytes, new_bytes):
    """The named refusal for a digest-changing delta whose line evidence
    surface shows no hunks (a trailing-newline change): never an
    exemption, never a vacuous row."""
    return cr.leg_reason(
        "classify",
        "bytes changed with no hunks: the digests differ (%s.. -> %s..) "
        "while the line evidence surface shows no hunks; the delta is "
        "never vacuously exempt"
        % (cr.sha256_hex(old_bytes)[:12], cr.sha256_hex(new_bytes)[:12]))


def exempt_verdict(hunks):
    """(True, prefixed success message) when every hunk carries the
    comment-only class and at least one hunk exists; otherwise (False,
    prefixed refusal naming the unclassified hunk(s) and their violated
    rules)."""
    if not hunks:
        return False, cr.leg_reason(
            "classify", "no hunks on the evidence surface to exempt")
    bad = [hunk for hunk in hunks
           if hunk["class"] == CLASS_UNCLASSIFIED]
    if bad:
        return False, cr.leg_reason(
            "classify",
            "hunk(s) not exempt: " + "; ".join(
                "%s %s" % (hunk["header"], hunk["reason"])
                for hunk in bad))
    return True, "%sdelta fully exempt: every hunk carries the " \
                 "comment-only class" % cr.MARKER_PREFIX


def classify_delta(old_bytes, new_bytes, path):
    """(hunks, ok, message) for one file's whole delta: identical bytes
    pass with no hunks; a digest-changing delta with no hunks takes the
    bytes-changed-no-hunks refusal; a hunk-carrying delta whose two sides
    disagree on the trailing newline is unclassified (the line model
    drops that fact); otherwise exempt_verdict grades the hunk list."""
    hunks = classify_lines(old_bytes, new_bytes, path)
    if not hunks:
        if cr.sha256_hex(old_bytes) != cr.sha256_hex(new_bytes):
            return hunks, False, bytes_changed_no_hunks_reason(
                old_bytes, new_bytes)
        return hunks, True, cr.MARKER_PREFIX + "no delta: identical bytes"
    if old_bytes.endswith(b"\n") != new_bytes.endswith(b"\n"):
        return hunks, False, cr.leg_reason(
            "classify",
            "the delta changes the trailing newline while the line "
            "evidence surface shows hunk(s); the newline fact is "
            "invisible to the line model, so the delta is unclassified")
    ok, message = exempt_verdict(hunks)
    return hunks, ok, message


# ---------------------------------------------------------------------------
# Diff parsing, the seal-path exclusion, and the certified-range legs
# ---------------------------------------------------------------------------


def _diff_section_path(value):
    if value is None:
        return None
    value = value.split("\t")[0]
    if value == "/dev/null":
        return None
    if len(value) > 1 and value.startswith('"') and value.endswith('"'):
        decoded = _decode_c_quoted(value[1:-1])
        if decoded is None:
            return None
        value = decoded
    if value.startswith("a/") or value.startswith("b/"):
        value = value[2:]
    return value


# The standard C escapes git emits inside a C-quoted diff path token;
# every other byte travels as a three-digit octal escape.
_C_UNESCAPES = {"a": "\a", "b": "\b", "f": "\f", "n": "\n", "r": "\r",
                "t": "\t", "v": "\v", "\\": "\\", '"': '"'}


def _decode_c_quoted(token):
    """The UTF-8 path text for the inner body of a C-quoted diff path
    token, or None when the token carries an unknown escape or the bytes
    do not decode as UTF-8 (the path cannot be resolved to content)."""
    buf = bytearray()
    i = 0
    while i < len(token):
        ch = token[i]
        if ch != "\\":
            buf.extend(ch.encode("utf-8"))
            i += 1
            continue
        if i + 1 >= len(token):
            return None
        nxt = token[i + 1]
        if nxt in "01234567":
            end = i + 1
            while end < len(token) and end < i + 4 \
                    and token[end] in "01234567":
                end += 1
            buf.append(int(token[i + 1:end], 8))
            i = end
            continue
        mapped = _C_UNESCAPES.get(nxt)
        if mapped is None:
            return None
        buf.extend(mapped.encode("utf-8"))
        i += 2
    try:
        return buf.decode("utf-8")
    except UnicodeDecodeError:
        return None


# The markers of a pure rename or mode section: no content headers, no
# content to classify. new file mode and deleted file mode are not here:
# an added or deleted binary file carries them beside a binary payload.
_RENAME_MODE_PREFIXES = ("rename from ", "rename to ",
                         "old mode ", "new mode ")


def diff_sections(diff_bytes):
    """Per-file section records of a unified diff text: ``old`` and
    ``new`` (the decoded paths; None for /dev/null and for a quoted
    token that does not decode), ``old_devnull`` and ``new_devnull``,
    ``content`` (the section carries ``---``/``+++`` headers), and
    ``rename_or_mode`` (the section carries rename or mode markers). A
    section with content headers and no resolvable path, a section with
    neither content headers nor rename or mode markers (a binary or
    unparseable section), and a pure rename or mode section refuse the
    hop fail-closed at the consumer."""
    text = diff_bytes.decode("utf-8", "replace")
    sections = []
    current = None
    for line in text.splitlines():
        if line.startswith("diff --git "):
            if current is not None:
                sections.append(current)
            current = {"old": None, "new": None,
                       "old_devnull": False, "new_devnull": False,
                       "content": False, "rename_or_mode": False}
        elif current is None:
            continue
        elif line.startswith("--- "):
            current["old"] = _diff_section_path(line[4:])
            current["old_devnull"] = line[4:].split("\t")[0] == "/dev/null"
            current["content"] = True
        elif line.startswith("+++ "):
            current["new"] = _diff_section_path(line[4:])
            current["new_devnull"] = line[4:].split("\t")[0] == "/dev/null"
            current["content"] = True
        elif line.startswith(_RENAME_MODE_PREFIXES):
            current["rename_or_mode"] = True
    if current is not None:
        sections.append(current)
    return sections


def section_refusal(section):
    """The fail-closed refusal for a section that names no resolvable
    content, or None when the section yields a usable path. A pure
    rename or mode section refuses too (r1 fold): rename and mode
    changes are runtime or path visible, never comment content, so the
    hop refuses unclassified instead of the section dropping from the
    verdict."""
    if section["content"]:
        if section["old"] is None and section["new"] is None:
            return ("the diff section carries content headers but no "
                    "resolvable path: the C-quoted path form does not "
                    "decode")
        return None
    if section["rename_or_mode"]:
        return ("the diff section is a pure rename or mode change with "
                "no content headers: rename and mode changes are runtime "
                "or path visible and never classify as comment-only; the "
                "hop fails closed")
    return ("the diff section carries no parseable ---/+++ headers (a "
            "binary or unparseable section); the hop fails closed")


def parse_diff_paths(diff_bytes):
    """(old_path, new_path) per file section of a unified diff text; None
    stands for /dev/null on an added or deleted side and for a quoted
    path token that does not decode."""
    return [(section["old"], section["new"])
            for section in diff_sections(diff_bytes)]


def seal_excluded(path):
    """True for paths under the certification seal directory.
    The seal path is excluded from diff classification."""
    normalized = os.path.normpath(str(path)).replace(os.sep, "/")
    return normalized.startswith(cr.SEAL_DIR_RELPATH + "/")


def _read_side(repo, commit, path):
    """(bytes, absent, None) or (None, False, message). absent marks a
    path that has no listing at the commit (an added or deleted file
    side reads as empty bytes); a failing read behind a resolved commit
    is a git plumbing failure. The caller refuses a side the diff names
    that comes back absent."""
    listing = cr.git_text(repo, "ls-tree", commit, "--", path)
    if listing is None:
        return None, False, ("git ls-tree failed over the resolved commit "
                             "%s" % commit)
    if not listing.strip():
        return b"", True, None
    data = cr.blob_bytes(repo, commit, path)
    if data is None:
        return None, False, ("the blob %s:%s is unreadable: git plumbing "
                             "failed over resolved inputs" % (commit, path))
    return data, False, None


def _side_absent_refusal(path, side, commit):
    return ("the diff names %s on its %s side but no blob resolves at %s; "
            "the path cannot be resolved to content and the hop fails "
            "closed" % (path, side, commit))


NO_CLASSIFIABLE_REASON = ("bytes changed with no classifiable hunks: "
                          "every changed path is excluded (the seal "
                          "path), or its diff section is unparseable or "
                          "binary; a pure rename or mode section carries "
                          "its own refusal")


def hop_unclassified(repo, after_base, after_head, after_diff_bytes):
    """The unclassified verdicts for one correction hop: the returned
    list is empty when every classifiable hunk of the fix carries the
    comment-only class. The after diff's sections pick the files (the
    seal path is excluded; a binary or unparseable section, a section
    whose quoted path does not decode, and a side the diff names that
    resolves to no blob refuse). The blobs at the chained refs carry the
    per-language proof. The after base must chain from the certified
    head, so this diff is the fix itself."""
    verdicts = []
    classified = False
    for section in diff_sections(after_diff_bytes):
        refusal = section_refusal(section)
        if refusal is not None:
            verdicts.append(refusal)
            classified = True
            continue
        old, new = section["old"], section["new"]
        path = new if new is not None else old
        if path is None:
            continue
        if seal_excluded(path):
            continue
        classified = True
        before_path = old if old is not None else path
        after_path = new if new is not None else path
        old_bytes, old_absent, err = _read_side(repo, after_base,
                                                before_path)
        if err is None:
            new_bytes, new_absent, err = _read_side(repo, after_head,
                                                    after_path)
        if err is None and old_absent and old is not None:
            err = _side_absent_refusal(old, "before", after_base)
        if err is None and new_absent and new is not None:
            err = _side_absent_refusal(new, "after", after_head)
        if err is not None:
            verdicts.append("%s: %s" % (path, err))
            continue
        hunks, ok, message = classify_delta(old_bytes, new_bytes, path)
        if not ok:
            verdicts.append("%s: %s" % (path, message))
    if not classified:
        verdicts.append(NO_CLASSIFIABLE_REASON)
    return verdicts


def hop_classify(repo, after_base, after_head):
    """A corrections_record classify hook for one hop: the byte operands
    are already hash-bound by the verifier's digest-binding leg, so the
    verdict classifies from the after diff's paths and the blobs at the
    chained refs."""
    def classify(before_diff_bytes, after_diff_bytes):
        return hop_unclassified(repo, after_base, after_head,
                                after_diff_bytes)
    return classify


def _ref_rule_reason(rows, certified_range):
    """The certified-range ref rules: row 0's before refs equal the
    certified range, each before side chains from the previous hop's
    after head, and every after base equals its before head."""
    prev = None
    for index, row in enumerate(rows):
        if prev is None:
            sealed = (certified_range.get("base"),
                      certified_range.get("head"))
            before = (row["before_base"], row["before_head"])
            if before != sealed:
                return cr.leg_reason(
                    "seal", "row 0's before refs %s differ from the "
                            "certified range %s" % (before, sealed))
        elif row["before_base"] != prev["after_head"]:
            return cr.leg_reason(
                "linkage", "row %d's before base is not the previous "
                           "row's after head" % index)
        if row["after_base"] != row["before_head"]:
            return cr.leg_reason(
                "linkage", "row %d's after base is not the before head"
                % index)
        prev = row
    return None


def verify_code_corrections(repo, artifact_path, round_number,
                            source_digest, rows, certified_range,
                            slug=None, head="HEAD", seal_repo=None,
                            witness_path=None):
    """The code-family corrections verifier: the certified-range ref
    rules, then corrections_record's verifier legs (anchor, seal
    integrity, digest binding to the re-derived diffs, linkage, hop
    dating, terminal), then the classification leg re-run per hop over
    the fix diff re-derived from git with the seal path excluded. An
    operator-acked row's receipt resolves out of band against the
    witness record path injected by the caller (None keeps the unattended
    default: the receipt leg refuses and re-review applies).
    Returns (True, prefixed success message) or (False, prefixed refusal
    naming the violated rule)."""
    try:
        for row in rows:
            cr.validate_row(row, cr.FAMILY_CODE)
    except cr.CorrectionsSchemaError as exc:
        return False, str(exc)
    if rows:
        reason = _ref_rule_reason(rows, certified_range)
        if reason is not None:
            return False, reason
    ok, message = cr.verify_corrections(
        repo, artifact_path, cr.FAMILY_CODE, round_number, source_digest,
        rows, certified_range=certified_range, head=head, slug=slug,
        seal_repo=seal_repo, witness_path=witness_path)
    if not ok or not rows:
        return ok, message
    for index, row in enumerate(rows):
        after_diff = cr.diff_bytes(repo, row["after_base"],
                                   row["after_head"])
        if after_diff is None:
            return False, cr.leg_reason(
                "classify", "git plumbing failed while re-deriving the "
                            "hop %d fix diff" % index)
        verdicts = hop_unclassified(repo, row["after_base"],
                                    row["after_head"], after_diff)
        if verdicts:
            return False, cr.leg_reason(
                "classify", "hunk(s) not exempt at hop %d: %s"
                % (index, verdicts[0]))
    return True, message


