#!/usr/bin/env python3
"""Code delta classifier for graded review certification.

The classifier buckets each hunk of a code delta into the single exempt
class of the binding's Exempt class term, ``comment-only``, or refuses it
as ``unclassified``:

- ``comment-only``: per-language proof that every changed line's code
  content is byte-identical and only comment content differs, trailing
  comments included. The Python proof runs over tokenize comment spans
  plus AST docstring awareness; the Bash proof tracks quote and heredoc
  state, and a ``#`` starts a comment only at a word boundary outside
  quotes (a mid-word hash is code content, never a trailing comment). A
  trailing comment change is exempt only when the code portion before the
  comment is byte-identical.

Every refusal below is unclassified, fail-closed:

- docstring and string-literal content: runtime visible, and docstrings
  carry doctests that execute;
- the closed directive-comment family (``noqa``, ``eslint-disable``,
  ``type: ignore``, ``shellcheck disable``, ``fmt:``, ``isort:``,
  ``ruff: noqa``, ``pylint: disable``, ``flake8: noqa``), added, changed,
  or removed on a changed line;
- PEP 263 encoding declarations on lines 1-2 in any spelling: runtime
  load-bearing and decode-bearing;
- heredoc bodies (data, not comments), shebang lines (runtime
  load-bearing), and blank-line changes (no exempt class covers them);
- generated files whose content carries a generated-file marker header;
- unsupported languages (Python and Bash are supported at birth;
  everything else fails closed); and non-UTF-8 content.

Library surface: ``classify_lines(old_bytes, new_bytes, path)`` returns
the hunk list; ``classify_delta`` grades a whole file delta;
``verify_code_corrections`` runs the certified-range ref rules and
corrections_record's verifier legs over a code corrections chain, with
the classification leg re-run per hop over the fix diff re-derived from
git. The seal path (``.ai-playbook/review-certs/``) is excluded from
diff classification. A diff section without parseable ``---``/``+++``
headers refuses the hop fail-closed, and a pure rename or mode section
refuses too (rename and mode changes are runtime or path visible, never
comment content); a C-quoted path token (git's core.quotePath form) is decoded
before
resolution, and a side the diff names that resolves to no blob refuses
the hop instead of reading as empty bytes. A review certified over a
working-tree diff or a materialized patch records no range, has no refs
to chain, and stays unclassifiable (the default re-review applies).
Refusals start with MARKER_PREFIX and contain no banned literal.
Decoding is UTF-8 strict. The hunk scaffolding mirrors
plan_delta_classifier's contract so both families emit identically
shaped rows. Consumers: the staging validator re-runs the classifier
over bytes re-derived from git.
"""

import argparse
import ast
import difflib
import io
import json
import os
import re
import sys
import tokenize
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import corrections_record as cr

CLASS_COMMENT_ONLY = "comment-only"
CLASS_UNCLASSIFIED = "unclassified"
EXEMPT_CLASSES = (CLASS_COMMENT_ONLY,)

LANGUAGE_BY_SUFFIX = {".py": "python", ".sh": "bash", ".bash": "bash"}

# Generated-file marker headers, matched case-insensitively within the
# first lines of either side of the delta.
GENERATED_MARKERS = ("do not edit", "@generated", "generated by")
_GENERATED_HEADER_LINES = 5

# The PEP 263 encoding declaration; valid only on physical lines 1-2.
_PEP263_RE = re.compile(r"^[ \t\f]*#.*?coding[:=][ \t]*([-_.a-zA-Z0-9]+)")

# The closed directive-comment family, matched against a changed line's
# comment text in either language.
_DIRECTIVE_PATTERNS = (
    ("noqa", re.compile(r"#\s*noqa\b")),
    ("eslint-disable", re.compile(r"#\s*eslint-disable")),
    ("type: ignore", re.compile(r"#\s*type:\s*ignore")),
    ("shellcheck disable", re.compile(r"#\s*shellcheck\s+disable")),
    ("fmt:", re.compile(r"#\s*fmt:")),
    ("isort:", re.compile(r"#\s*isort:")),
    ("ruff: noqa", re.compile(r"#\s*ruff:\s*noqa")),
    ("pylint: disable", re.compile(r"#\s*pylint:\s*disable")),
    ("flake8: noqa", re.compile(r"#\s*flake8:\s*noqa")),
)

# A heredoc opener outside quotes: << or <<- with optional whitespace
# after the operator and after the dash, and a word delimiter optionally
# single- or double-quoted (bash accepts << EOF, <<- EOF, << "EOF").
# Whitespace never precedes the dash (bash rejects that spelling). A
# leading third '<' (here-string) never matches.
_HEREDOC_RE = re.compile(r"<<\s*(-?)\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\2")

REASON_CODE_CHANGED = ("the line's code content changed; only comment "
                       "content may differ")
REASON_CODE_ADDED = "a code line was added; only comment content may differ"
REASON_CODE_REMOVED = ("a code line was removed; only comment content "
                       "may differ")
REASON_BLANK = ("a blank-line change carries no comment content; no exempt "
                "class covers blank-line changes in code")
REASON_DOCSTRING = ("docstring or string-literal content is runtime visible "
                    "and docstrings carry doctests that execute")
REASON_COOKIE = ("an encoding declaration on lines 1-2 is runtime "
                 "load-bearing and decode-bearing in every PEP 263 spelling")
REASON_SHEBANG = ("the shebang line is runtime load-bearing; a shebang "
                  "change is not comment-only")
REASON_HEREDOC = "heredoc bodies are data, not comments"
REASON_QUOTE = "the line lies inside a quote continuation"


def _directive_member(comment):
    if not comment:
        return None
    for member, pattern in _DIRECTIVE_PATTERNS:
        if pattern.search(comment):
            return member
    return None


def _directive_reason(member):
    return ("the directive-comment family is closed: a %s comment edit is "
            "unclassified" % member)


